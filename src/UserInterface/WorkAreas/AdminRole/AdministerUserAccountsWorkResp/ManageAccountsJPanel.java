    private void populateTable() {
        DefaultTableModel model = (DefaultTableModel) tblAccounts.getModel();
        model.setRowCount(0);
        accounts = business.getUserAccountDirectory().getUserAccountList();
        for (UserAccount ua : accounts) {
            Object[] row = new Object[4];
            row[0] = ua.getUserLoginName();
            row[1] = ua.getPersonId();
            row[2] = ua.getAssociatedPersonProfile().getPerson().getFullName();
            row[3] = ua.getRole();
            model.addRow(row);
        }
    }

    // The account of the selected row, or null if nothing is selected
    private UserAccount getSelectedAccount() {
        int row = tblAccounts.getSelectedRow();
        if (row < 0) {
            return null;
        }
        return accounts.get(row);
    }

