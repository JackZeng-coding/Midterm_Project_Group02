    private void btnChangePasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChangePasswordActionPerformed
        // TODO add your handling code here:
        UserAccount ua = getSelectedAccount();
        if (ua == null) {
            warn("Please select an account first.");
            return;
        }
        String pw = new String(pwdNewPassword.getPassword());
        if (pw.length() < 6) {   // same rule as Register Persons
            warn("Password must be at least 6 characters.");
            return;
        }
        ua.setPassword(pw);
        pwdNewPassword.setText("");
        JOptionPane.showMessageDialog(this, "Password changed for " + ua.getUserLoginName() + ".",
                "Done", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnChangePasswordActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        UserAccount ua = getSelectedAccount();
        if (ua == null) {
            warn("Please select an account first.");
            return;
        }

        if (ua == currentAccount) {
            warn("You cannot delete the account you are logged in with.");
            return;
        }
        int choice = JOptionPane.showConfirmDialog(this,
                "Delete account \"" + ua.getUserLoginName() + "\"?\n"
                + "Only the login is removed; the person's records are kept.",
                "Confirm delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        business.getUserAccountDirectory().removeUserAccount(ua);
        populateTable();
        JOptionPane.showMessageDialog(this, "Account deleted.", "Done", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnDeleteActionPerformed

