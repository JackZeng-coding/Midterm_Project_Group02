    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        String first = txtFirstName.getText().trim();
        String last = txtLastName.getText().trim();
        String email = txtEmail.getText().trim();
        String role = (String) cmbRole.getSelectedItem();
        String username = txtUsername.getText().trim();
        String password = new String(pwdPassword.getPassword());

        // 1. Required fields
        if (first.isEmpty() || last.isEmpty() || email.isEmpty() || username.isEmpty() || password.isEmpty()) {
            warn("All fields are required.");
            return;
        }
        // 2. Formats (same rules as the Student profile page, so the app is consistent)
        String nameFormat = "[A-Za-z]+([ '-][A-Za-z]+)*";
        if (!first.matches(nameFormat) || !last.matches(nameFormat)) {
            warn("Names may only contain letters, spaces, ' or -.");
            return;
        }
        if (!email.matches("[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+")) {
            warn("Please enter a valid email address.");
            return;
        }
        if (password.length() < 6) {
            warn("Password must be at least 6 characters.");
            return;
        }
        // 3. Username must be unique
        if (business.getUserAccountDirectory().isUsernameTaken(username)) {
            warn("Username \"" + username + "\" already exists.");
            return;
        }

        // 4. Create: person master data → role profile (both sides) → login account
        Person p = business.getPersonDirectory().newPerson(first, last, email);
        Profile profile;
        if (role.equals("Student")) {
            profile = business.getStudentDirectory().newStudentProfile(p);
        } else if (role.equals("Faculty")) {
            profile = business.getFacultyDirectory().newFacultyProfile(p);

        } else {

            profile = business.getEmployeeDirectory().newEmployeeProfile(p);
        }
        business.getUserAccountDirectory().newUserAccount(profile, username, password);

        JOptionPane.showMessageDialog(this, "Registered " + p.getFullName() + " as " + role
                + " (ID " + p.getPersonId() + ").", "Done", JOptionPane.INFORMATION_MESSAGE);
        clearForm();


    }//GEN-LAST:event_btnRegisterActionPerformed

