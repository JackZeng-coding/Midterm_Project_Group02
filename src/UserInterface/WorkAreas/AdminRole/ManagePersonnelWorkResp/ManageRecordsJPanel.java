    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        Profile p = getSelectedProfile();
        if (p == null) {
            warn("Please select a record first.");
            return;
        }
        Person person = p.getPerson();
        int n = countCourseRecords(p);
        if (n > 0) {
            warn(person.getFullName() + " has " + n + " course record(s) and cannot be deleted.\n"
                    + "Course history must be kept.");
            return;
        }
        int choice = JOptionPane.showConfirmDialog(this,
                "Delete " + person.getFullName() + " (ID " + person.getPersonId() + ")?\n"
                + "The login account and the " + role.toLowerCase() + " record will be removed.",
                "Confirm delete", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        // 1. login account
        UserAccount ua = business.getUserAccountDirectory().findUserAccount(person.getPersonId());
        if (ua != null) {
            business.getUserAccountDirectory().removeUserAccount(ua);
        }
        // 2. role profile, both sides
        if (p instanceof StudentProfile) {
            business.getStudentDirectory().removeStudent((StudentProfile) p);
        } else if (p instanceof FacultyProfile) {
            business.getFacultyDirectory().removeFaculty((FacultyProfile) p);
        }
        // 3. person master data
        business.getPersonDirectory().removePerson(person);
        if (p == selected) {
            clearDetails();
        }
        populateTable();
        JOptionPane.showMessageDialog(this, "Deleted.", "Done", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        if (selected == null) {
            warn("Please select a record and click View Details first.");
            return;
        }
        String first = txtFirstName.getText().trim();
        String last = txtLastName.getText().trim();
        String email = txtEmail.getText().trim();
        if (first.isEmpty() || last.isEmpty() || email.isEmpty()) {
            warn("All fields are required.");
            return;
        }
        String nameFormat = "[A-Za-z]+([ '-][A-Za-z]+)*";
        if (!first.matches(nameFormat) || !last.matches(nameFormat)) {
            warn("Names may only contain letters, spaces, ' or -.");
            return;
        }
        if (!email.matches("[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+")) {
            warn("Please enter a valid email address.");
            return;
        }
        Person person = selected.getPerson();   
        person.setFirstName(first);
        person.setLastName(last);
        person.setEmail(email);
        setEditing(false);
        populateTable();
        JOptionPane.showMessageDialog(this, "Saved.", "Done", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnSaveActionPerformed


