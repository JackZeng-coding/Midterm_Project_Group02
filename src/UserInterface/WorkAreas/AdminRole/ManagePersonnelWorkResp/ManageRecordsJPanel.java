    private void populateTable() {
        DefaultTableModel model = (DefaultTableModel) tblRecords.getModel();
        model.setRowCount(0);
        // A list of StudentProfile is not a list of Profile, so copy them into a Profile list
        profiles = new ArrayList<>();
        if (role.equals("Student")) {
            profiles.addAll(business.getStudentDirectory().getStudentList());
        } else {
            profiles.addAll(business.getFacultyDirectory().getFacultyList());
        }
        for (Profile p : profiles) {
            Person person = p.getPerson();
            Object[] row = new Object[4];
            row[0] = person.getPersonId();
            row[1] = person.getFullName();
            row[2] = person.getEmail();
            row[3] = countCourseRecords(p);
            model.addRow(row);
        }
    }

    // Records that block deletion: courses taken (student, all semesters) or classes taught (faculty)
    private int countCourseRecords(Profile p) {
        if (p instanceof StudentProfile) {
            StudentProfile sp = (StudentProfile) p;
            return sp.getUniversityRecord().getCourseList().size();
        }
        if (p instanceof FacultyProfile) {
            FacultyProfile fp = (FacultyProfile) p;
            return fp.getUniversityRecord().getCourseOffers().size();
        }
        return 0;
    }

    private Profile getSelectedProfile() {
        int row = tblRecords.getSelectedRow();
        if (row < 0) {
            return null;
        }
        return profiles.get(row);
    }

