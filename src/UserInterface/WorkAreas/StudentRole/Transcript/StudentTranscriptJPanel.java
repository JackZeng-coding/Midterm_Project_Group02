    private void loadTranscript() {
        // Check if bridge is connected
        info5100.university.example.Persona.StudentProfile record = student.getUniversityRecord();
        if(record == null) {
            System.out.println("Error: Student doesn't have a University Record.");
            return;
        }
        // Get list of courses taken
        ArrayList<SeatAssignment> courses = record.getCourseList();
        // Check if the student has a transcript list?
        if (courses == null || courses.isEmpty()) {
            System.out.println("Notice: Student hasn't registered for any courses yet.");
            return;
        }
        // Setup Table
        DefaultTableModel model = (DefaultTableModel) tblTranscript.getModel();
        model.setRowCount(0); // Clear table
        
        float totalQualityPoints = 0f;
        int totalCredits = 0;
        
        for (SeatAssignment sa : courses) {
            // check if SeatAssignment or Course is missing and skip
            if (sa == null || sa.getAssociatedCourse() == null) {
                continue;
            }
            String courseNumber = sa.getAssociatedCourse().getCOurseNumber();
            String courseName = sa.getAssociatedCourse().getName();
            int credits = sa.getAssociatedCourse().getCredits();
            float grade = sa.getGrade();
            
            String letter = (grade <= 0f) ? "IP" : toLetterGrade(grade);
            
            Object[] row = new Object[4];
        
            row[0] = courseNumber;
            row[1] = courseName;
            row[2] = credits;
            row[3] = letter; // changed to letter grade instead of numeric
            model.addRow(row);
            
            rowAssignments.add(sa);
            
            if (grade > 0f) {
                totalQualityPoints += grade * credits;
                totalCredits += credits;
            }
        }
        if (totalCredits > 0) {
            float gpa = totalQualityPoints / totalCredits;
            lblGpa.setText(String.format("GPA: %.2f (%d graded credits)", gpa, totalCredits));
        } else {
            lblGpa.setText("GPA: - (no graded courses yet)");
        }
    }
    private String toLetterGrade(float g) {
        // Maps 0.0-4.0 GPA value to letter grade (subject to change if necessary).
        if (g >= 3.8f) return "A";
        if (g >= 3.5f) return "A-";
        if (g >= 3.15f) return "B+";
        if (g >= 2.85f) return "B";
        if (g >= 2.5f)  return "B-";
        if (g >= 2.15f) return "C+";
        if (g >= 1.85f) return "C";
        if (g >= 1.5f)  return "C-";
        if (g >= 1.0f)  return "D";
        return "F";
    }


