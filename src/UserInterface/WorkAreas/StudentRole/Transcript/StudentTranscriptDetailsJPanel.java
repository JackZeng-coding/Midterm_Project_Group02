    private void populate() {
        if (assignment == null || assignment.getAssociatedCourse() == null) {
            titleLabel.setText("No course selected");
            return;
        }
        info5100.university.example.Persona.StudentProfile record = student.getUniversityRecord();
        
        String semester = (record != null) ? record.getSemesterFor(assignment) : null;
        if (semester == null) semester = "-";
        
        String number = assignment.getAssociatedCourse().getCOurseNumber();
        String name = assignment.getAssociatedCourse().getName();
        int credits = assignment.getAssociatedCourse().getCredits();
        float grade = assignment.getGrade();
        String letter = (grade <= 0f) ? "In progress" : toLetterGrade(grade);
        String numeric = (grade <= 0f) ? "-" : String.format("%.2f", grade);
        
        String instructor = "-";
        try {
            FacultyProfile fp = assignment.getCourseOffer().getFacultyProfile();
            if (fp != null && fp.getPerson() != null) {
                instructor = fp.getPerson().getPersonId();
            }
        } catch (Exception ignore) {
            // no faculty assigned to offer
        }
        titleLabel.setText(number + " - " + name);
        txtSemester.setText(semester);
        txtCredits.setText(String.valueOf(credits));
        txtGrade.setText(letter + " (" + numeric + ")");
        txtInstructor.setText(instructor);
        
    }
    
    private String toLetterGrade(float g) {
        // Maps 0.0-4.0 GPA value to letter grade (subject to change if necessary).
        if (g >= 3.8f) return "A";
        if (g >= 3.5f) return "A-";
        if (g >= 3.15f) return "B+";
        if (g >= 2.85f) return "B";
        if (g >= 2.5f)  return "B-";
        if (g >= 2.15f) return "C+";
        if (g >= 1.85f) return "C";
        if (g >= 1.5f)  return "C-";
        if (g >= 1.0f)  return "D";
        return "F";
    }

