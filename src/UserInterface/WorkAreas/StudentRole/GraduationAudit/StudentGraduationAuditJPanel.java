    private void runAudit() {
        info5100.university.example.Persona.StudentProfile record = student.getUniversityRecord();
        Department dept = business.getDepartment();
        Degree degree = (dept != null) ? dept.getDegree() : null;
        
        // Header
        Person p = student.getPerson();
        txtStudent.setText("Student: " + (p!= null? p.getFullName() : "-"));
        txtDegree.setText("Degree: " + (degree !=null ? degree.getTitle(): "-"));
        
        // Null handler
        if (record == null || degree == null) {
            txtVerdict.setText("Audit unavailable");
            txtCredits.setText("");
            ((DefaultTableModel) tblCore.getModel()).setRowCount(0);
            ((DefaultTableModel) tblElective.getModel()).setRowCount(0);
            return;
        }
        // Courses student has taken
        
        ArrayList<SeatAssignment> taken = record.getCourseList();
        Set<String> takenNumbers = new HashSet<>();
        for (SeatAssignment sa : taken) {
            if (sa == null || sa.getAssociatedCourse() == null) continue;
            takenNumbers.add(sa.getAssociatedCourse().getCOurseNumber());
        }
        // Table data for Core courses taken
        DefaultTableModel coreModel = (DefaultTableModel) tblCore.getModel();
        coreModel.setRowCount(0);
        int coreSatisfied = 0;
        for (Course c : degree.getCorelist()) {
            boolean ok = takenNumbers.contains(c.getCOurseNumber());
            if (ok) coreSatisfied++;
            
            Object[] row = new Object[4];
            row[0] = ok ? "✓" : "✗";
            row[1] = c.getCOurseNumber();
            row[2] = c.getName();
            row[3] = c.getCredits() + " cr";
            
            coreModel.addRow(row);
        }
        // Table data for Elective courses taken
        DefaultTableModel electiveModel = (DefaultTableModel) tblElective.getModel();
        electiveModel.setRowCount(0);
        int electiveSatisfied = 0;
        for (Course c : degree.getElectives()) {
            boolean ok = takenNumbers.contains(c.getCOurseNumber());
            if (ok) electiveSatisfied++;
            
            Object[] row = new Object[4];
            row[0] = ok ? "✓" : "✗";
            row[1] = c.getCOurseNumber();
            row[2] = c.getName();
            row[3] = c.getCredits() + " cr";
            
            electiveModel.addRow(row);
        }
        // Credits check to display if students meet requirements
        int totalCredits = degree.getTotalCreditsTaken(taken);
        int required = degree.getRequiredCredits();
        boolean creditsOk = totalCredits >= required;
        txtCredits.setText((creditsOk ? "✓ " : "✗ ") + "Credits: " + totalCredits + " / " + required);
        
        // Verdict display if student can graduate according to degree requiremenets
        boolean ready = degree.isStudentReadyToGraduate(record);
        
        int coreTotal = degree.getCorelist().size();
        int elecTotal = degree.getElectives().size();
        txtVerdict.setText((ready ? "READY TO GRADUATE" : "REQUIREMENTS NOT MET") + " - Core " + coreSatisfied + "/" + coreTotal + " . Electives " + electiveSatisfied + "/" + elecTotal + " . Credits " + totalCredits + "/" + required);
    }

