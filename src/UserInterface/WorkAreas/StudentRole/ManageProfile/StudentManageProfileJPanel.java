    private void btnBackActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBackActionPerformed
        // TODO add your handling code here:
        if (editing) {
            int choice = javax.swing.JOptionPane.showConfirmDialog(this, "You have unsaved changes. Do you want to discard them?", "Unsaved Changes", javax.swing.JOptionPane.YES_NO_OPTION, javax.swing.JOptionPane.WARNING_MESSAGE);
            if (choice != javax.swing.JOptionPane.YES_OPTION) {
                return; // User chose no and we stay on panel
            }
        }
        // If user chooses yes leave page and don't save data
        CardSequencePanel.remove(this); 
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);
    }//GEN-LAST:event_btnBackActionPerformed

    private void btnEditSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditSaveActionPerformed
        // TODO add your handling code here:
        if (!editing) {
            if(student.getPerson() == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "No person record to edit.", "Cannot edit", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
            // Enter edit mode
            setEditing(true);
            return;
        }
        // if Person is null do NOT enter edit mode
        Person p = student.getPerson();
        if (p == null) {
            setEditing(false);
            return;
        }
        String first = txtFirstName.getText().trim();
        String last = txtLastName.getText().trim();
        String email = txtEmail.getText().trim();
        
        // Check for empty Fields
        if (first.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "First name is required", "Missing Information", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (last.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Last name is required", "Missing Information", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (email.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Email is required", "Missing Information", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Check if name is formated properly.
        String nameFormat = "[A-Za-z]+([ '-][A-Za-z]+)*";
        
        if (!first.matches(nameFormat)) {
            javax.swing.JOptionPane.showMessageDialog(this, "First name may contain letters, spaces, hyphens, and apostrophes only " + "(must start and end with a letter)", "Invalid first name", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!last.matches(nameFormat)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Last name may contain letters, spaces, hyphens, and apostrophes only " + "(must start and end with a letter)", "Invalid last name", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Check if email is formated properly.
        
        if (!email.contains("@") || !email.contains(".")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid email address", "Invalid email", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Push data into object
        p.setFirstName(first);
        p.setLastName(last);
        p.setEmail(email);
        
        javax.swing.JOptionPane.showMessageDialog(this, "Profile updated", "Saved", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        populate();
        setEditing(false);
    }//GEN-LAST:event_btnEditSaveActionPerformed


