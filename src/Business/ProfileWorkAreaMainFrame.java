    private void LoginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LoginButtonActionPerformed
        // TODO add your handling code here:
        //      WorkAreaJPanel ura = new WorkAreaJPanel(workareajpanl);

        String un = UserNameTextField.getText().trim();     // trim() removes leading/trailing spaces, so "   " counts as empty
        String pw = new String(PasswordField.getPassword());            // the password is NOT trimmed: spaces can be part of a password

        // Validation: both fields are required
        if (un.isEmpty() || pw.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please enter both username and password.",
                    "Login", JOptionPane.WARNING_MESSAGE);
            return;
        }

        UserAccountDirectory uad = business.getUserAccountDirectory();
        UserAccount useraccount = uad.AuthenticateUser(un, pw);
        if (useraccount == null) {
            JOptionPane.showMessageDialog(this,
                    "Invalid username or password.",
                    "Login failed", JOptionPane.ERROR_MESSAGE);
            PasswordField.setText("");   // clear the password so the user can retry

            return;
        }
        StudentWorkAreaJPanel studentworkareajpanel;
        FacultyWorkAreaJPanel facultyworkarea;
        AdminRoleWorkAreaJPanel adminworkarea;
        String r = useraccount.getRole();
        Profile profile = useraccount.getAssociatedPersonProfile();

        // Authorization: the profile type decides which work area this account may open
        if (profile instanceof EmployeeProfile) {

            adminworkarea = new AdminRoleWorkAreaJPanel(business, CardSequencePanel);
            CardSequencePanel.removeAll();
            CardSequencePanel.add("Admin", adminworkarea);
            ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);

        } else if (profile instanceof StudentProfile) {

            StudentProfile spp = (StudentProfile) profile;
            studentworkareajpanel = new StudentWorkAreaJPanel(business, spp, CardSequencePanel);
            CardSequencePanel.removeAll();
            CardSequencePanel.add("student", studentworkareajpanel);
            ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);

        } else if (profile instanceof FacultyProfile) {

            FacultyProfile fpp = (FacultyProfile) profile;   // cast: the type was checked on the line above
            facultyworkarea = new FacultyWorkAreaJPanel(business, fpp, CardSequencePanel);
            CardSequencePanel.removeAll();
            CardSequencePanel.add("faculty", facultyworkarea);
            ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);

        } else {
            // A role without a work area must not get in
            JOptionPane.showMessageDialog(this,
                    "This account's role has no work area yet.",
                    "Access denied", JOptionPane.ERROR_MESSAGE);
            PasswordField.setText("");
            return;
        }

        setLoggedIn(true);   // lock the login form only after a work area is actually shown


    }//GEN-LAST:event_LoginButtonActionPerformed

